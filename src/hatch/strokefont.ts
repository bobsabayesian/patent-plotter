const SPACE = 2;
const GAP = 1.2;

export interface PlacedGlyph { x: number; strokes: XY[][] }

/** Lay out `text` left to right (design units). Unknown characters are skipped; width includes trailing gap. */
export function layoutText(text: string): { glyphs: PlacedGlyph[]; width: number } {
  const glyphs: PlacedGlyph[] = [];
  let x = 0;
  // "<3" is a heart
  const chars = [...text.replace(/<3/g, '♥').toLowerCase()];
  for (const ch of chars) {
    if (ch === ' ') { x += SPACE; continue; }
    const strokes = GLYPHS[ch];
    if (!strokes) continue;
    let maxX = 0;
    for (const s of strokes) for (const [px] of s) maxX = Math.max(maxX, px);
    glyphs.push({ x, strokes });
    x += maxX + GAP;
  }
  return { glyphs, width: x };
}

